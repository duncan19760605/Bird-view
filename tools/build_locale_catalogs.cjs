// Build offline catalogs from checked-in JSON plus curated terminology.
// --simplify requires build/i18n-tools/opencc.cjs once; normal builds do not.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'data/locales');
const read=name=>JSON.parse(fs.readFileSync(path.join(dir,name),'utf8'));
const sources=read('source.json'),catalogs={en:read('en.json'),ja:read('ja.json'),ko:read('ko.json')};
const editorial={en:{},ja:{},ko:{}};
for(const line of fs.readFileSync(path.join(dir,'editorial.tsv'),'utf8').split(/\r?\n/)){
  if(!line||line.startsWith('#'))continue;
  const columns=line.split('|');if(columns.length!==4)throw new Error('Invalid editorial row: '+line);
  ['en','ja','ko'].forEach((l,i)=>editorial[l][columns[0]]=columns[i+1]);
}
const birds=JSON.parse(fs.readFileSync(path.join(root,'data/birds.json'),'utf8'));
const names=read('bird-name-sources.json').birds;
const fallbackNames={ja:[],ko:[]};
for(const [id,bird] of Object.entries(birds)){
  catalogs.en[bird.zh]=bird.en;
  for(const language of ['ja','ko']){
    const label=names[id]?.labels?.[language];
    catalogs[language][bird.zh]=label||bird.en;
    if(!label)fallbackNames[language].push(id);
  }
}
for(const language of ['en','ja','ko']){
  const catalog=catalogs[language];
  // Correct context errors in the translation draft before editorial overrides.
  for(const [source,translation] of Object.entries(catalog)){
    let value=translation;
    if(language==='en'){
      if(source.includes('收音'))value=value.replace(/radio/gi,'microphone input');
      value=value.replace(/background correction/gi,'background calibration').replace(/picture book/gi,'bird collection').replace(/illustrated book/gi,'collection');
      if(source.includes('閾值')||source.includes('倍率'))value=value.replace(/global magnification/gi,'global multiplier');
      if(source.includes('→'))value=value.replace(/your /gi,'its ').replace(/mouth/gi,'bill');
    }
    if(language==='ja'&&source.includes('收音'))value=value.replace(/無線/g,'マイク入力');
    if(language==='ko'&&source.includes('收音'))value=value.replace(/라디오/g,'마이크 입력');
    catalog[source]=value;
  }
  Object.assign(catalog,editorial[language]);
  // Recompose HTML from original tags and translated text nodes. Never translate tags.
  for(const source of sources.filter(s=>s.includes('<'))){
    catalog[source]=source.split(/(<[^>]*>)/g).map(part=>{
      if(part.startsWith('<')||!/[\u3400-\u9fff]/u.test(part))return part;
      if(catalog[part])return catalog[part];
      const trimmed=part.trim();
      if(catalog[trimmed])return part.replace(trimmed,catalog[trimmed]);
      throw new Error(`${language}: missing HTML text translation: ${part}`);
    }).join('');
  }
}
if(process.argv.includes('--simplify')){
  const converter=require('../build/i18n-tools/opencc.cjs').Converter({from:'tw',to:'cn'});
  catalogs['zh-Hans']=Object.fromEntries(sources.map(source=>[source,converter(source)]));
  for(const [id,bird] of Object.entries(birds))if(names[id]?.labels?.['zh-cn'])catalogs['zh-Hans'][bird.zh]=names[id].labels['zh-cn'];
}else catalogs['zh-Hans']=read('zh-Hans.json');
const tokens=s=>(s.match(/\{\d+\}/g)||[]).sort().join('|');
for(const [language,catalog] of Object.entries(catalogs)){
  for(const source of sources){
    if(typeof catalog[source]!=='string'||!catalog[source])throw new Error(`${language}: missing ${source}`);
    if(tokens(source)!==tokens(catalog[source]))throw new Error(`${language}: placeholders changed: ${source}`);
    if(JSON.stringify(source.match(/<[^>]*>/g))!==JSON.stringify(catalog[source].match(/<[^>]*>/g)))throw new Error(`${language}: HTML changed: ${source}`);
  }
  fs.writeFileSync(path.join(dir,language+'.json'),JSON.stringify(catalog,null,2)+'\n');
}
fs.writeFileSync(path.join(dir,'zh-Hant.json'),JSON.stringify(Object.fromEntries(sources.map(s=>[s,s])),null,2)+'\n');
fs.writeFileSync(path.join(root,'js/locale-catalogs.js'),'// Generated by tools/build_locale_catalogs.cjs; no online runtime service.\nexport default '+JSON.stringify(catalogs)+';\n');
fs.writeFileSync(path.join(dir,'translation-status.json'),JSON.stringify({date:'2026-11-07',sourceCount:sources.length,locales:['zh-Hant','en','ja','zh-Hans','ko'],missing:0,placeholders:'verified',htmlStructure:'verified',birdNameFallbacks:fallbackNames,notes:'Public strings translated at build time; gameplay terminology curated in editorial.tsv. Bird names use scientific-name-linked Wikidata labels; missing local names retain the existing English name. Narrative prose has not received native-speaker review.'},null,2)+'\n');
console.log('Built five offline locales for',sources.length,'source strings.');
