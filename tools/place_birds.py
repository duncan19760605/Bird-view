def main(path):
    p = Path(path)
    lv = json.loads(p.read_text(encoding="utf-8"))
    scene = Image.open(ROOT / "assets/realistic" / lv["scene"])
    W, H = scene.size
    plc = PLACEMENTS[p.name]
    birds = []
    bird_dir = lv.get("birdDir", "birds")
    for sp, (fx, fy, wpx, flip, hint, *extra) in plc.items():
        im = Image.open(ROOT / "assets/realistic" / bird_dir / f"{sp}.png")
        hpx = wpx * im.height / im.width
        birds.append({
            "species": sp,
            "x": round(fx / W, 4),
            "y": round((fy - hpx / 2) / H, 4),
            "scale": round(wpx / W, 4),
            "art": "cutout",
            "flip": flip,
            "hint": hint,
        })
        if extra:
            birds[-1]["behavior"], birds[-1]["stay"] = extra
    lv["birds"] = birds
    p.write_text(json.dumps(lv, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{p.name}: {len(birds)} birds placed on {W}x{H}")

if __name__ == "__main__":
    main(sys.argv[1])
